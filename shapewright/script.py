"""shapewright.script - turn a Scene's op log into a runnable build123d script."""

from __future__ import annotations

HEADER = '''"""
Generated by the shapewright MCP server.

A plain build123d (algebra mode) script - edit it directly or re-run it.
    python this_file.py
"""

from build123d import *  # noqa: F401,F403
from shapewright.select import select  # the same edge/face selector used by shapewright

'''


def to_python(scene, export_dir: str | None = None) -> str:
    lines = [HEADER]
    lines.extend(scene.code or ["# (no operations recorded)"])
    lines.append("")
    if export_dir:
        lines.append("import os")
        lines.append(f"os.makedirs({export_dir!r}, exist_ok=True)")
        for name in scene.names():
            lines.append(
                f"export_stl({name}, os.path.join({export_dir!r}, {name + '.stl'!r}))"
            )
            lines.append(
                f"export_step({name}, os.path.join({export_dir!r}, {name + '.step'!r}))"
            )
        lines.append("")
    return "\n".join(lines)
